const TYPE_LABEL: Record<string, string> = {
  essay_smart: 'مقالي ذكي',
  essay_reasoning: 'مقالي استدلال وفهم',
}

function clean(s: string | null | undefined): string {
  return (s ?? '').trim()
}

export function buildGradingText(items: EssayItem[]): string {
  const n = items.length
  const summaryParts: string[] = []
  for (let i = 1; i <= n; i++) summaryParts.push(`س${i}=…`)
  const summary = `الملخص: ${summaryParts.join(' | ')} | المجموع=…`

  const blocks = items.map((it, idx) => {
    const ans = clean(it.answer)
      .replace(/<\/?إجابة_الطالب>/g, '')
    return [
      `=== س${idx + 1} (${TYPE_LABEL[it.type] ?? it.type}) — الدرجة الكاملة: ${it.score} ===`,
      `السؤال: ${clean(it.text)}`,
      `الإجابة النموذجية: ${clean(it.modelAnswer) || '(غير مسجلة)'}`,
      `معيار التصحيح: ${clean(it.criteria) || '(غير مسجل)'}`,
      '<إجابة_الطالب>',
      ans || '(لا إجابة)',
      '</إجابة_الطالب>',
    ].join('\n')
  })

  return `${PROMPT_HEAD}${summary}\n\nالبيانات:\n\n${blocks.join('\n\n')}\n`
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text)
    return true
  } catch {
    try {
      const ta = document.createElement('textarea')
      ta.value = text
      ta.style.position = 'fixed'
      ta.style.opacity = '0'
      document.body.appendChild(ta)
      ta.select()
      const ok = document.execCommand('copy')
      document.body.removeChild(ta)
      return ok
    } catch {
      return false
    }
  }
}